/**
 * `npm run seo`: keeps the SEO head block, sitemap.xml and robots.txt in step with js/config.js.
 * For every root *.html page it (re)writes a managed block between <!-- seo:start --> and <!-- seo:end -->:
 * canonical URL, favicon set, Open Graph and Twitter tags (title and description are read from the page itself),
 * plus JSON-LD (Organization and ProfessionalService) on the home page.
 * Change the domain in config.site.url, then run this script again. Safe to re-run.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { config } = await import(pathToFileURL(path.join(root, 'js/config.js')).href);
const site = config.site.url.replace(/\/+$/, '');
const abs = (p) => `${site}/${p.replace(/^\/+/, '')}`;
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const START = '<!-- seo:start (generated by `npm run seo`, do not edit by hand) -->';
const END = '<!-- seo:end -->';

// Pages that should not be listed in the sitemap (case-study.html is a template driven by ?slug=).
const SKIP_SITEMAP = new Set(['case-study.html']);

const c = config.contact;
const sameAs = Object.values(c.social || {}).filter(Boolean);
const orgLd = {
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'Organization',
      '@id': `${site}/#organization`,
      name: config.brand.name,
      url: `${site}/`,
      logo: abs('assets/logo/narris-logo-nav.png'),
      description: config.brand.metaDescriptor,
      email: c.email || undefined,
      telephone: c.phoneIntl || undefined,
      ...(sameAs.length ? { sameAs } : {}),
    },
    {
      '@type': 'ProfessionalService',
      '@id': `${site}/#service`,
      name: config.brand.name,
      url: `${site}/`,
      image: abs(config.site.ogImage),
      description: config.brand.metaDescriptor,
      email: c.email || undefined,
      telephone: c.phoneIntl || undefined,
      areaServed: 'Worldwide',
      address: { '@type': 'PostalAddress', addressLocality: 'Nairobi', addressCountry: 'KE', ...(c.address ? { streetAddress: c.address } : {}) },
      ...(c.hours ? { openingHours: c.hours } : {}),
      parentOrganization: { '@id': `${site}/#organization` },
    },
  ],
};

const files = (await readdir(root)).filter((f) => f.endsWith('.html')).sort();
for (const f of files) {
  let html = await readFile(path.join(root, f), 'utf8');
  const title = /<title>([^<]*)<\/title>/.exec(html)?.[1];
  const desc = /<meta name="description" content="([^"]*)"/.exec(html)?.[1];
  if (!title || !desc) { console.warn(`seo: ${f} lacks a title or description, skipped`); continue; }
  const url = f === 'index.html' ? `${site}/` : abs(f);

  const block = [
    START,
    `  <link rel="canonical" href="${url}">`,
    `  <link rel="icon" href="favicon.ico" sizes="48x48">`,
    `  <link rel="icon" type="image/png" sizes="32x32" href="assets/icons/favicon-32.png">`,
    `  <link rel="icon" type="image/png" sizes="16x16" href="assets/icons/favicon-16.png">`,
    `  <meta property="og:type" content="website">`,
    `  <meta property="og:site_name" content="${esc(config.brand.name)}">`,
    `  <meta property="og:title" content="${title}">`,
    `  <meta property="og:description" content="${desc}">`,
    `  <meta property="og:url" content="${url}">`,
    `  <meta property="og:image" content="${abs(config.site.ogImage)}">`,
    `  <meta property="og:image:width" content="1200">`,
    `  <meta property="og:image:height" content="630">`,
    `  <meta property="og:image:alt" content="${esc(config.brand.name)} logo">`,
    `  <meta name="twitter:card" content="summary_large_image">`,
    `  <meta name="twitter:title" content="${title}">`,
    `  <meta name="twitter:description" content="${desc}">`,
    `  <meta name="twitter:image" content="${abs(config.site.ogImage)}">`,
    ...(f === 'index.html' ? [`  <script type="application/ld+json">${JSON.stringify(orgLd)}</script>`] : []),
    `  ${END}`,
  ].join('\n');

  // Drop any earlier managed block, the old generic icon link and the Phase 0 canonical/TODO placeholders.
  html = html
    .replace(new RegExp(`[ \\t]*${START.replace(/[.*+?^${}()|[\]\\`]/g, '\\$&')}[\\s\\S]*?${END}\\n?`), '')
    .replace(/[ \t]*<link rel="icon" type="image\/png" href="assets\/logo\/narris-logo-bg\.png">\n/, '')
    .replace(/[ \t]*<link rel="canonical"[^>]*>\n/, '')
    .replace(/[ \t]*<!-- TODO\(client\): canonical URL[^>]*-->\n/, '');

  const anchor = '<link rel="apple-touch-icon" href="assets/icons/apple-touch-icon.png">';
  if (!html.includes(anchor)) { console.warn(`seo: ${f} has no apple-touch-icon anchor, skipped`); continue; }
  html = html.replace(anchor, `${anchor}\n  ${block}`);
  await writeFile(path.join(root, f), html);
}

/* sitemap.xml and robots.txt */
const today = new Date().toISOString().slice(0, 10);
// Pages carrying a noindex robots tag (e.g. Gen Z Research until content sign-off) are kept out of the sitemap.
const noindex = new Set();
for (const f of files) if (/<meta name="robots" content="[^"]*noindex/.test(await readFile(path.join(root, f), 'utf8'))) noindex.add(f);
const urls = files.filter((f) => !SKIP_SITEMAP.has(f) && !noindex.has(f)).map((f) => (f === 'index.html' ? `${site}/` : abs(f)));
await writeFile(
  path.join(root, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`)
    .join('\n')}\n</urlset>\n`
);
await writeFile(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);
console.log(`seo: ${files.length} pages updated, ${urls.length} URLs in sitemap.xml (site: ${site})`);
